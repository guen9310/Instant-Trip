import * as React from "react"
import { cn } from "@/shared/utils"

const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement> & { selected?: boolean; interactive?: boolean }
>(({ className, selected, interactive, ...props }, ref) => (
  <div
    ref={ref}
    className={cn(
      "rounded-[12px] border-[0.5px] border-border bg-surface text-text-primary shadow-sm transition-all",
      selected && "border-[1.5px] border-primary bg-primary/5 shadow-md",
      interactive && "cursor-pointer active:scale-[0.97] transition-transform duration-150",
      className
    )}
    {...props}
  />
))
Card.displayName = "Card"

